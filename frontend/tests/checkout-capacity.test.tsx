import { act, fireEvent, screen } from '@testing-library/react';
import { expect, it, vi } from 'vitest';
import CartPage from '@/app/cart/page';
import { cartApi, addressApi, orderApi } from '@/lib/api';
import { useAuthStore } from '@/store/useAuthStore';
import { useLocaleStore } from '@/store/useLocaleStore';
import { readCanonicalCart } from '@/lib/cart-sync';
import { captureHandler, render, settle } from './helpers';
const router = vi.hoisted(() => ({ push: vi.fn() }));
vi.mock('next/navigation', () => ({ useRouter: () => router, useSearchParams: () => new URLSearchParams(window.location.search) }));
vi.mock('@/lib/logger', () => ({ logger: { error: vi.fn() } }));
vi.mock('@/lib/api', () => ({ cartApi: { list: vi.fn() }, addressApi: { list: vi.fn() }, orderApi: { preview: vi.fn(), create: vi.fn() } }));
it('requires an explicit batch choice for 101 variants and never requests oversized quotes', async () => {
  useAuthStore.getState().login({ user_id: 1, username: 'Buyer', email: 'buyer@example.test' }, 'capacity-session');
  const rows = Array.from({ length: 101 }, (_, index) => ({ cart_id: index + 1, product_id: 1, sku_id: index + 1, title: `Variant ${index + 1}`, quantity: 2, price: 10, stock: 5 }));
  vi.mocked(cartApi.list).mockResolvedValue({ items: rows });
  vi.mocked(addressApi.list).mockResolvedValue({ addresses: [{ address_id: 41, receiver_name: 'Buyer', phone: '13800138000', province: null, city: null, district: null, detail_address: 'Street' }] });
  vi.mocked(orderApi.preview).mockImplementation(async input => ({ original_amount: input.items.length * 20, discount_amount: 0, total_amount: input.items.length * 20, coupon: null, available_coupons: [] }));
  render(<CartPage />); await settle();
  expect(orderApi.preview).not.toHaveBeenCalled();
  expect(screen.getByRole('checkbox', { name: '全选' })).toBeDisabled();
  const extra = captureHandler(screen.getByRole('checkbox', { name: '选择 Variant 101' }), 'onChange');
  fireEvent.click(screen.getByRole('button', { name: '选择前 100 项' })); await settle();
  expect(orderApi.preview).toHaveBeenLastCalledWith({ items: rows.slice(0, 100).map(row => ({ product_id: row.product_id, sku_id: row.sku_id, quantity: 2 })) });
  expect(screen.getByRole('checkbox', { name: '选择 Variant 101' })).toBeDisabled();
  await extra(); await settle();
  expect(vi.mocked(orderApi.preview).mock.calls.every(([input]) => input.items.length <= 100)).toBe(true);
  fireEvent.click(screen.getByRole('checkbox', { name: '选择 Variant 1' })); await settle();
  expect(screen.getByRole('checkbox', { name: '选择 Variant 101' })).toBeEnabled();
  fireEvent.click(screen.getByRole('checkbox', { name: '选择 Variant 101' })); await settle();
  expect(vi.mocked(orderApi.preview).mock.lastCall?.[0].items.at(-1)?.sku_id).toBe(101);
  // A stock change must release its selection slot after the canonical cart refresh.
  vi.mocked(cartApi.list).mockResolvedValue({ items: rows.map(row => row.sku_id === 2 ? { ...row, available: false, stock: 0 } : row) });
  await act(async () => { await readCanonicalCart(undefined, { fresh: true }); }); await settle();
  expect(screen.getByRole('checkbox', { name: '选择 Variant 2' })).toBeDisabled();
  expect(screen.getByRole('checkbox', { name: '选择 Variant 1' })).toBeEnabled();
  fireEvent.click(screen.getByRole('checkbox', { name: '选择 Variant 1' })); await settle();
  expect(vi.mocked(orderApi.preview).mock.lastCall?.[0].items).toHaveLength(100);
  act(() => useLocaleStore.getState().setLocale('en')); await settle();
  expect(screen.getByText('Selected 100 / 100 products or variants')).toBeInTheDocument();
});
